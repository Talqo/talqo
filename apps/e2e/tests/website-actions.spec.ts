import { expect } from "@playwright/test"

import { test } from "./chat-embed"
import { web } from "./i18n"
import { ADMIN, openDashboard } from "./log-in"

test("website-action instructions are prefilled, editable, and restored explicitly", async ({ page, chatEmbed }) => {
	await openDashboard(page, ADMIN, `/dashboard/agent/${chatEmbed.agentId}?tab=mcp`)
	const enabled = page.getByRole("switch", { name: web("pageControl.title") })
	const instructions = page.getByRole("textbox", { name: web("pageControl.instructions") })
	const save = page.getByRole("button", { name: web("agentConfig.save"), exact: true })
	const restore = page.getByRole("button", { name: web("pageControl.restoreDefaults") })
	await expect(enabled).toBeChecked()
	await expect(instructions).not.toHaveValue("")
	const defaults = await instructions.inputValue()
	await page.getByRole("tab", { name: web("agentConfig.tabConfiguration") }).click()
	const prompt = page.getByRole("textbox", { name: web("agentFields.systemPrompt"), exact: true })
	const savedPrompt = await prompt.inputValue()
	await prompt.fill("An unsaved instruction draft.")
	await page.getByRole("tab", { name: web("agentConfig.tabMcp") }).click()
	await instructions.fill("Ask before submitting any form.")
	await save.click()
	await expect(page.getByText(web("agentConfig.saved"), { exact: true })).toBeVisible()
	await page.getByRole("tab", { name: web("agentConfig.tabConfiguration") }).click()
	await expect(prompt).toHaveValue("An unsaved instruction draft.")
	await prompt.fill(savedPrompt)
	await page.getByRole("tab", { name: web("agentConfig.tabMcp") }).click()
	await page.reload()
	await expect(instructions).toHaveValue("Ask before submitting any form.")
	await enabled.click()
	await expect(instructions).toBeHidden()
	await save.click()
	await expect(page.getByText(web("agentConfig.saved"), { exact: true })).toBeVisible()
	await page.reload()
	await expect(enabled).not.toBeChecked()
	await enabled.click()
	await expect(instructions).toHaveValue("Ask before submitting any form.")
	await restore.click()
	await expect(instructions).toHaveValue(defaults)
	await save.click()
	await expect(page.getByText(web("agentConfig.saved"), { exact: true })).toBeVisible()
	await page.reload()
	await expect(instructions).toHaveValue(defaults)
	await expect(enabled).toBeChecked()
})
